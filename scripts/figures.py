def _heat_colour(value, low, high):
    if value is None:
        return FAINT, 0.15
    span = max(1e-9, high - low)
    strength = max(0.0, min(1.0, (value - low) / span))
    if value >= high - span * 0.15:
        return ACCENT, 0.22 + 0.62 * strength
    if value >= low + span * 0.5:
        return TEAL, 0.22 + 0.62 * strength
    if value >= low + span * 0.25:
        return AMBER, 0.24 + 0.55 * strength
    return DANGER, 0.24 + 0.5 * strength


