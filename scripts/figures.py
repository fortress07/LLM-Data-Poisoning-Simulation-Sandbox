def figure_dose_response() -> str:
    payload = load("dose_response")
    fit = payload["dose_response"]
    points = sorted(fit["points"], key=lambda item: item["rate"])
    groups = {round(group["attack.poison_rate"], 6): group for group in payload["groups"]}
    width, height = 900, 410
    pad = {"top": 44, "right": 34, "bottom": 96, "left": 66}
    inner_w = width - pad["left"] - pad["right"]
    inner_h = height - pad["top"] - pad["bottom"]
    logs = [math.log10(point["rate"]) for point in points]
    low, high = min(logs) - 0.12, max(logs) + 0.12

    def x_of(value):
        return pad["left"] + (value - low) / (high - low) * inner_w

    def y_of(value):
        return pad["top"] + (1 - max(0.0, min(1.0, value))) * inner_h

    parts: List[str] = []
    for level in (0.0, 0.25, 0.5, 0.75, 1.0):
        y = y_of(level)
        parts.append(line(pad["left"], y, width - pad["right"], y))
        parts.append(text(pad["left"] - 10, y + 4, "%d%%" % round(level * 100), size=11, fill=FAINT, anchor="end"))
    for point in points:
        x = x_of(math.log10(point["rate"]))
        parts.append(
            text(x, height - pad["bottom"] + 19, "%.2f%%" % (point["rate"] * 100), size=10.5, fill=FAINT, anchor="middle")
        )

    accuracy = []
    for point in points:
        group = groups.get(round(point["rate"], 6))
        if group:
            accuracy.append((x_of(math.log10(point["rate"])), y_of(group["cda_mean"])))
    if accuracy:
        path = " ".join(
            "%s%.1f,%.1f" % ("M" if index == 0 else "L", x, y) for index, (x, y) in enumerate(accuracy)
        )
        parts.append(
            "<path d='%s' fill='none' stroke='%s' stroke-width='2.5' stroke-dasharray='6 4'/>" % (path, TEAL)
        )

    curve = []
    for index in range(121):
        value = low + (high - low) * index / 120
        exponent = -fit["slope"] * (value - fit["midpoint_log10"])
        asr = fit["upper"] / (1 + math.exp(max(-60.0, min(60.0, exponent))))
        curve.append("%s%.1f,%.1f" % ("M" if index == 0 else "L", x_of(value), y_of(asr)))
    parts.append("<path d='%s' fill='none' stroke='%s' stroke-width='3'/>" % (" ".join(curve), ACCENT))

    critical = math.log10(fit["critical_rate"])
    if low <= critical <= high:
        x = x_of(critical)
        parts.append(line(x, pad["top"], x, height - pad["bottom"], AMBER, 1.8, "5 4"))
        parts.append(
            text(x + 8, pad["top"] + 16, "critical rate %.3f%%" % (fit["critical_rate"] * 100), size=11.5, fill=AMBER, weight="700")
        )

    for point in points:
        x = x_of(math.log10(point["rate"]))
        y = y_of(point["asr"])
        error = point.get("stderr") or 0.0
        if error:
            parts.append(line(x, y_of(point["asr"] - error), x, y_of(point["asr"] + error), ROSE, 2.5))
        parts.append("<circle cx='%.1f' cy='%.1f' r='5' fill='%s'/>" % (x, y, ROSE))

    parts.append(text(pad["left"], 24, "Attack success against poison budget", size=14.5, weight="700"))
    parts.append(
        text(width - pad["right"], 24, "6 seeds per point, r squared %.3f" % fit["r_squared"], size=11.5, fill=FAINT, anchor="end")
    )
    parts.append(
        text(pad["left"] + inner_w / 2, height - pad["bottom"] + 44, "share of the training set that is poisoned", size=11.5, fill=FAINT, anchor="middle")
    )
    legend_y = height - 22
    parts.append("<circle cx='%.1f' cy='%.1f' r='5' fill='%s'/>" % (pad["left"] + 4, legend_y - 4, ROSE))
    parts.append(text(pad["left"] + 16, legend_y, "measured attack success", size=11.5, fill=FAINT))
    parts.append(line(pad["left"] + 190, legend_y - 4, pad["left"] + 214, legend_y - 4, TEAL, 2.5, "6 4"))
    parts.append(text(pad["left"] + 222, legend_y, "clean accuracy, unchanged throughout", size=11.5, fill=FAINT))
    return write("dose-response.svg", "\n".join(parts), width, height)


