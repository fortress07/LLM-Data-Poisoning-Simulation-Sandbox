        parts.append(rect(x - 22, bar_top, 44, top + chart_h - bar_top, colour, rx=5, opacity=0.85 if detected else 0.45))
        parts.append(text(x, bar_top - 8, "%.3f" % p, size=11, fill=colour if detected else FAINT, anchor="middle", weight="700"))
