    parts.append(text(left + 8, threshold - 8, "p = 0.05", size=11, fill=DANGER, weight="700"))
    slot = chart_w / len(rows)
    for index, row in enumerate(rows):
        x = left + index * slot + slot / 2
        p = row["median_p"]
        detected = row["flagged_at_05"] > 0
        colour = TEAL if detected else FAINT
