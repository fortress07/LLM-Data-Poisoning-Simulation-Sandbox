def use_theme(name: str) -> None:
    palette = PALETTES[name]
    globals().update(
        INK=palette["ink"],
        FAINT=palette["faint"],
        GRID=palette["grid"],
        ACCENT=palette["accent"],
        ROSE=palette["rose"],
        TEAL=palette["teal"],
        AMBER=palette["amber"],
        DANGER=palette["danger"],
        CHIP=palette["chip"],
        PANEL=palette["panel"],
        SUFFIX="" if name == "light" else "-dark",
    )


def load(name: str) -> Dict[str, Any]:
    with open(os.path.join(DATA, "%s.json" % name), "r", encoding="utf-8") as handle:
        return json.load(handle)


def write(name: str, body: str, width: int, height: int) -> str:
    os.makedirs(ASSETS, exist_ok=True)
    stem, extension = os.path.splitext(name)
    path = os.path.join(ASSETS, "%s%s%s" % (stem, SUFFIX, extension))
    document = (
        "<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 %d %d' width='%d' height='%d' "
        "role='img'>\n%s\n</svg>\n" % (width, height, width, height, body)
    )
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(document)
    return path


def escape(value: Any) -> str:
    return (
        str(value)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def text(x, y, value, size=12, fill=None, anchor="start", weight="400"):
    return (
        "<text x='%.1f' y='%.1f' %s font-size='%s' fill='%s' text-anchor='%s' "
        "font-weight='%s'>%s</text>"
        % (x, y, FONT, size, fill or INK, anchor, weight, escape(value))
    )


def rect(x, y, w, h, fill, rx=3, opacity=1.0):
    return "<rect x='%.1f' y='%.1f' width='%.1f' height='%.1f' rx='%d' fill='%s' opacity='%.2f'/>" % (
        x,
        y,
        max(0.0, w),
        max(0.0, h),
        rx,
        fill,
        min(1.0, opacity),
    )


def line(x1, y1, x2, y2, stroke=None, width=1, dash=""):
    extra = " stroke-dasharray='%s'" % dash if dash else ""
    return "<line x1='%.1f' y1='%.1f' x2='%.1f' y2='%.1f' stroke='%s' stroke-width='%s'%s/>" % (
        x1,
        y1,
        x2,
        y2,
        stroke or GRID,
        width,
        extra,
    )


def panel(x, y, w, h, colour, opacity=0.09, radius=10, stroke=0.5):
    body = rect(x, y, w, h, colour, rx=radius, opacity=opacity * PANEL)
    if stroke:
        body += (
            "<rect x='%.1f' y='%.1f' width='%.1f' height='%.1f' rx='%d' fill='none' "
            "stroke='%s' stroke-width='1.4' opacity='%.2f'/>" % (x, y, w, h, radius, colour, stroke)
        )
    return body


def arrow(x1, y1, x2, y2, colour=None, dash=""):
    colour = colour or FAINT
    body = line(x1, y1, x2, y2, colour, 1.5, dash)
    if abs(y2 - y1) < 0.5:
        head = "<path d='M%.1f %.1f l-7 -4.5 l0 9 z' fill='%s'/>" % (x2, y2, colour)
    else:
        head = "<path d='M%.1f %.1f l-4.5 -7 l9 0 z' fill='%s'/>" % (x2, y2, colour)
    return body + head


